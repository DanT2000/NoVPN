package ru.appswire.novpn.core

/** Какие серверы приложение может выбирать само, а какие — только человек. */
object ServerPolicy {
    /** Значок домашнего сервера, который админ ставит в панели (имя «🏠 HomeVPN»). */
    private const val HOME = "🏠"

    /**
     * Домашний сервер (значок 🏠 в начале имени) — только ручной выбор. Это выход в
     * домашнюю сеть, а не аварийный: автоподбор при сбое сервера, возврат с резерва и
     * сервер по умолчанию на новой установке его не берут. Выбранный вручную — держим.
     */
    fun isManualOnly(name: String): Boolean = name.trimStart().startsWith(HOME)
}
