package ru.appswire.novpn.core

/** Признаки работоспособности сервера по живому трафику (без Android — проверяется тестами). */
object Health {
    /**
     * Получил ли сервер новые данные между двумя снимками соединений через него
     * (id соединения → принятые байты). Новое соединение с данными или прирост у
     * старого — сервер реально отдаёт трафик. Без прошлого снимка (null) ответа нет:
     * давно открытое соединение с когда-то полученными байтами не доказывает, что
     * сервер работает сейчас.
     */
    fun flowed(prev: Map<String, Long>?, now: Map<String, Long>): Boolean {
        if (prev == null) return false
        return now.any { (id, down) -> down > (prev[id] ?: 0L) }
    }
}
